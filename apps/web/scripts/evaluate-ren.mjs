#!/usr/bin/env node
/**
 * Runs REN's evaluation suites and prints the results.
 *
 *   pnpm --filter @nn/web evaluate
 *
 * The numbers this prints are the only ones NN is entitled to quote about
 * REN. A capability nobody measured is a capability nobody can defend.
 *
 * It runs through vitest rather than importing the TypeScript directly,
 * because the suites import NN's own modules by their `@/` alias and vitest
 * already resolves them. No build step, no second toolchain.
 */
import { spawnSync } from "node:child_process";
import { writeFileSync, unlinkSync } from "node:fs";
import { join } from "node:path";

const harness = join(process.cwd(), "src", "lib", "ren", "evaluate.generated.test.ts");

writeFileSync(harness, `import { describe, it } from "vitest";
import { runSuite, report } from "./evaluate";
import { SUITES } from "./suites";
import { understand } from "./understand";

/* Generated by scripts/evaluate-ren.mjs. Deleted when the run finishes. */
describe("REN evaluation", () => {
  it("runs every suite", async () => {
    const lines = [];
    for (const suite of SUITES) {
      const result = await runSuite(suite, understand, "no model; deterministic matcher only");
      lines.push(report(result));
    }
    console.log("\\n" + lines.join("\\n\\n") + "\\n");
  });
});
`);

const run = spawnSync(
  "./node_modules/.bin/vitest",
  ["run", "src/lib/ren/evaluate.generated.test.ts", "--silent=false"],
  { stdio: "inherit" },
);

try { unlinkSync(harness); } catch { /* already gone */ }
process.exit(run.status ?? 1);
