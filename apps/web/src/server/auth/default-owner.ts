import "server-only";

import type { OwnerRecord, RecoveryRecord } from "@nn/auth";

/**
 * NN's own default owner and password.
 *
 * The founder asked for the password to be a default of NN rather than
 * something Firebase has to answer for, and the reason is sound: they have
 * been locked out twice, both times because the *credential* was fine and
 * something around it was not. A password that only works when a particular
 * Firestore document exists is a password with a second, invisible
 * dependency — and that dependency has failed more often than the password.
 *
 * So the record can come from configuration. When Firestore holds a recovery
 * record, that one wins — it is the live credential and the founder can
 * change it. When Firestore holds nothing, NN falls back to what it was
 * deployed with, and sign-in works on a fresh deployment, an empty database
 * or a Firestore that cannot be reached.
 *
 * What this deliberately does **not** do:
 *
 * - **It does not move the check into the browser.** A password verified on
 *   the client has to ship something the client can check it against, which
 *   means publishing it to everyone who opens the site. The hash stays on the
 *   server, in configuration, exactly like `NN_BOOTSTRAP_SECRET`.
 * - **It does not replace the Firebase session.** Authorisation in NN is the
 *   Firestore security rules, and those are keyed to an authenticated uid.
 *   A sign-in that produced no Firebase session would be a sign-in after
 *   which nothing could be read or written — every one of the 34
 *   applications would open empty. The password proves who you are; the
 *   session is what makes your own records reachable.
 *
 * `NN_OWNER_RECOVERY` holds the scrypt record as JSON — salt, hash and
 * parameters, never the password. It is generated by
 * `firebase/scripts/make-owner-record.mjs`.
 */

/** A stable uid for the founder, used when NN has not been claimed yet. */
export const DEFAULT_OWNER_UID = "nn-owner";

/** Whether a configured default exists at all. */
export function defaultRecoveryConfigured(): boolean {
  return (process.env.NN_OWNER_RECOVERY ?? "").trim().length > 0;
}

/**
 * The recovery record NN was deployed with, or null.
 *
 * Parsed defensively: a malformed value is a configuration mistake, and the
 * right response is to behave as though none was configured rather than to
 * throw on every sign-in attempt. The failure is logged without any part of
 * the value, because a prefix of a hash is still a prefix of a hash.
 */
export function defaultRecoveryRecord(): RecoveryRecord | null {
  const raw = (process.env.NN_OWNER_RECOVERY ?? "").trim();
  if (raw.length === 0) return null;
  try {
    const parsed = JSON.parse(raw) as Partial<RecoveryRecord>;
    const ok =
      parsed.algorithm === "scrypt"
      && typeof parsed.salt === "string" && parsed.salt.length > 0
      && typeof parsed.hash === "string" && parsed.hash.length > 0
      && typeof parsed.N === "number" && typeof parsed.r === "number"
      && typeof parsed.p === "number" && typeof parsed.keyLength === "number";
    if (!ok) {
      console.error("NN_OWNER_RECOVERY is set but is not a scrypt record. Ignoring it.");
      return null;
    }
    const at = new Date(0).toISOString();
    return {
      schemaVersion: 1,
      algorithm: "scrypt",
      salt: parsed.salt as string,
      hash: parsed.hash as string,
      N: parsed.N as number,
      r: parsed.r as number,
      p: parsed.p as number,
      keyLength: parsed.keyLength as number,
      createdAt: parsed.createdAt ?? at,
      updatedAt: parsed.updatedAt ?? at,
      // Configuration cannot carry a failure count — there is nowhere to
      // write one back to. The per-caller rate limit still applies, and a
      // stored record (which does count failures) takes precedence whenever
      // one exists.
      failures: 0,
      lockedUntil: null,
    };
  } catch {
    console.error("NN_OWNER_RECOVERY is set but is not valid JSON. Ignoring it.");
    return null;
  }
}

/** The owner NN assumes when nothing has claimed it yet. */
export function defaultOwner(): OwnerRecord | null {
  if (!defaultRecoveryConfigured()) return null;
  return {
    uid: DEFAULT_OWNER_UID,
    claimedAt: new Date(0).toISOString(),
    credentialCount: 0,
  };
}
